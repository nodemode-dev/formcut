"""Every theme's text and accent colours meet WCAG AA (4.5:1) where they are used.

themes.css is generated by setup/gen_appearance.py; this reads the generated file,
so a change to the generator's ladder that lowers contrast fails here.
"""

import os
import re

import pytest

THEMES = os.path.join(os.path.dirname(__file__), "..", "frontend", "src", "styles", "themes.css")
SURFACES = ("--ground", "--inset", "--pane", "--float", "--control")


def _blocks():
    with open(THEMES, encoding="utf-8") as handle:
        css = handle.read()
    for name, body in re.findall(r':root\[data-theme="([a-z-]+)"\]\s*\{([^}]*)\}', css):
        yield name, {key: value.strip() for key, value in re.findall(r"(--[a-z-]+):\s*(#[0-9a-fA-F]{6})\s*;", body)}


def _luminance(colour):
    channels = [int(colour[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def _ratio(a, b):
    high, low = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


BLOCKS = dict(_blocks())


def test_every_profile_is_read():
    assert len(BLOCKS) == 29


@pytest.mark.parametrize("theme", sorted(BLOCKS))
def test_text_reads_at_aa_on_every_surface(theme):
    tokens = BLOCKS[theme]
    low = [
        (ink, surface, round(_ratio(tokens[ink], tokens[surface]), 2))
        for ink in ("--ink", "--ink-soft", "--ink-faint")
        for surface in SURFACES
    ]
    assert not [entry for entry in low if entry[2] < 4.5], low


@pytest.mark.parametrize("theme", sorted(BLOCKS))
def test_the_accent_reads_as_text_and_under_its_own_text(theme):
    tokens = BLOCKS[theme]
    as_text = {surface: round(_ratio(tokens["--cue"], tokens[surface]), 2) for surface in ("--ground", "--pane", "--float")}
    assert min(as_text.values()) >= 4.5, as_text
    assert _ratio(tokens["--on-cue"], tokens["--cue"]) >= 4.5
